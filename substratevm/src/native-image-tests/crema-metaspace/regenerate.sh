# Compiles the run-time payload classes of the Crema metaspace tests (the Java sources in this
# directory, which are not part of any mx project) and regenerates
# com.oracle.svm.test/src/com/oracle/svm/test/crema/CremaPayloads.java, which embeds their class
# files as byte arrays.
#
# Usage: JAVA_HOME=<jdk> bash regenerate.sh
set -euo pipefail

DIR=$(cd "$(dirname "$0")" && pwd)
OUT=$DIR/../../com.oracle.svm.test/src/com/oracle/svm/test/crema/CremaPayloads.java
CLASSES=$(mktemp -d)
trap 'rm -rf "$CLASSES"' EXIT

# -XDstringConcat=inline: no invokedynamic-based string concatenation, whose bootstrap may not be
# reachable in the image. --release 21: the oldest Java version supported by the test project.
"${JAVA_HOME:?JAVA_HOME must be set}/bin/javac" --release 21 -XDstringConcat=inline -d "$CLASSES" "$DIR/Hello.java" "$DIR/Holder.java"

byte_array() {
    od -An -v -t d1 "$1" | awk '{
        for (i = 1; i <= NF; i++) {
            if (n % 24 == 0) printf "%s                    ", (n == 0 ? "" : ",\n"); else printf ", ";
            printf "%s", $i;
            n++;
        }
    } END { printf "\n" }'
}

field() {
    local name=$1 class=$2
    cat <<EOF
    /**
     * Class file of {@code cremametaspace.$class}, compiled from
     * {@code src/native-image-tests/crema-metaspace/$class.java}.
     */
    // @formatter:off
    static final byte[] $name = {
$(byte_array "$CLASSES/cremametaspace/$class.class")
    };
    // @formatter:on
EOF
}

{
    sed -n '/^\/\*$/,/^ \*\/$/p' "$DIR/Hello.java"
    cat <<EOF
package com.oracle.svm.test.crema;

/**
 * Class files of the classes that the Crema metaspace tests define at run time.
 * <p>
 * The Java sources of these classes are in {@code src/native-image-tests/crema-metaspace/}, which
 * is not part of any mx project, so the classes are not compiled into the test image. Their class
 * files are embedded here as byte arrays instead and written to temporary class files at run time.
 * <p>
 * GENERATED by {@code src/native-image-tests/crema-metaspace/regenerate.sh}. Do not edit; change
 * the sources and rerun the script instead.
 */
final class CremaPayloads {
    private CremaPayloads() {
    }

    static final String PACKAGE = "cremametaspace";
    static final String HELLO = PACKAGE + ".Hello";
    static final String HOLDER = PACKAGE + ".Holder";

$(field HELLO_CLASS Hello)

$(field HOLDER_CLASS Holder)
}
EOF
} > "$OUT"
echo "wrote $OUT"
